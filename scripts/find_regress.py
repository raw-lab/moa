#!/usr/bin/env python3
"""Search tiny graphs where moa 1.x diverges from mcl; emit src/regress.rs with
mcl's recorded partitions. usage: find_regress.py V100 V110 OUT.rs"""
import os, random, subprocess, sys, json, tempfile

V100, V110, OUT = sys.argv[1:4]


def sets(t):
    return sorted(sorted(l.split("\t")) for l in t.strip("\n").split("\n") if l.strip())


def mcl(path, I, sch):
    a = ["mcl", path, "--abc", "-I", str(I), "-o", "-"] + sum((["-" + k, str(v)] for k, v in sch.items()), [])
    return sets(subprocess.run(a, capture_output=True, text=True).stdout)


def moa(binary, path, I, sch, style):
    a = [binary, "mcl", path, "-I", str(I)]
    for k, v in sch.items():
        if style == "v110" and k == "R":
            return None
        a += ["-" + k, str(v)]
    return sets(subprocess.run(a, capture_output=True, text=True).stdout)


TMP = os.path.join(tempfile.mkdtemp(prefix="moa-regress-"), "rg.abc")


def search(name, gen, schemes, tries=3000, want=1):
    found = []
    for t in range(tries):
        r = random.Random(hash((name, t)) & 0xffffffff)
        lines = gen(r)
        open(TMP, "w").write("".join(lines))
        for sch in schemes:
            for I in [1.4, 2.0, 3.0]:
                ref = mcl(TMP, I, sch)
                a = moa(V100, TMP, I, sch, "v100")
                b = moa(V110, TMP, I, sch, "v110")
                if a != ref and (b is None or b != ref):
                    found.append({"name": name, "abc": "".join(lines), "I": I, "scheme": sch, "mcl": ref,
                                  "v100": a, "v110": b})
                    if len(found) >= want:
                        return found
                    break
            else:
                continue
            break
    return found


def recip(r):
    n = r.randint(6, 10); out = []
    for i in range(n):
        for j in range(i + 1, n):
            if r.random() < .45:
                w = r.choice([1, 2, 3, 5, 8])
                out.append(f"v{i}\tv{j}\t{w}\n")
                out.append(f"v{j}\tv{i}\t{r.choice([1, 2, 3, 5, 8])}\n")
    return out


def tight(r):
    n = r.randint(10, 18); out = []
    for i in range(n):
        for j in range(i + 1, n):
            if r.random() < .4:
                out.append(f"t{i}\tt{j}\n")
    return out


def overlap(r):
    n = r.randint(6, 11); out = []
    for i in range(n):
        for j in range(i + 1, n):
            if r.random() < .35:
                out.append(f"o{i}\to{j}\t{r.choice([1, 1, 2, 3])}\n")
    return out


cases = []
cases += search("max-merge of reciprocal edges", recip, [{}], want=1)
cases += search("select/recover ties", tight, [{"P": 300, "S": 4, "R": 6}, {"P": 500, "S": 5, "R": 9}], want=1)
cases += search("interpretation overlap (cut)", overlap, [{}], want=1)

# Plus fixed structural cases (recorded live from mcl; no divergence needed).
fixed = [
    ("friends", open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "examples", "friends.abc")).read(), 2.0, {}),
    ("multi-component", "a\tb\t3\nb\tc\t3\na\tc\t3\nc\td\t0.2\nd\te\t4\ne\tf\t4\nd\tf\t4\nx\ty\t1\nsolo\tsolo\t1\np\tq\t2\nq\tr\t2\n", 2.0, {}),
    ("prune-only scheme", "".join(f"p{i}\tp{j}\t{(i * j) % 5 + 1}\n" for i in range(14) for j in range(i + 1, 14) if (i + 2 * j) % 3 == 0), 2.0, {"P": 40, "S": 0, "R": 0}),
    ("select without recover", "".join(f"s{i}\ts{j}\n" for i in range(16) for j in range(i + 1, 16) if (i * 7 + j * 3) % 4 == 0), 1.6, {"P": 1000, "S": 3, "R": 0}),
]
for name, abc, I, sch in fixed:
    open(TMP, "w").write(abc)
    cases.append({"name": name, "abc": abc, "I": I, "scheme": sch, "mcl": mcl(TMP, I, sch),
                  "v100": moa(V100, TMP, I, sch, "v100"), "v110": moa(V110, TMP, I, sch, "v110")})


def rs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t").replace("\n", "\\n") + '"'


with open(OUT, "w") as f:
    f.write("//! Regression corpus for `moa doctor`: tiny graphs with partitions recorded\n"
            "//! from the reference `mcl 22-282` binary (generated by scripts/find_regress.py).\n"
            "//! The first three are graphs on which moa 1.0.0 and 1.1.0 both disagreed with mcl.\n\n")
    f.write("pub struct Case {\n    pub name: &'static str,\n    pub abc: &'static str,\n    pub inflation: f64,\n"
            "    pub prune: usize,\n    pub select: usize,\n    pub recover: usize,\n    pub expected: &'static [&'static [&'static str]],\n    pub old_1_0_0_ok: bool,\n    pub old_1_1_0_ok: Option<bool>,\n}\n\n")
    f.write("pub const CASES: &[Case] = &[\n")
    for c in cases:
        s = c["scheme"]
        exp = "&[" + ", ".join("&[" + ", ".join(rs(x) for x in cl) + "]" for cl in c["mcl"]) + "]"
        b = "None" if c["v110"] is None else f"Some({str(c['v110'] == c['mcl']).lower()})"
        f.write(f"    Case {{\n        name: {rs(c['name'])},\n        abc: {rs(c['abc'])},\n        inflation: {c['I']},\n"
                f"        prune: {s.get('P', 10000)},\n        select: {s.get('S', 1100)},\n        recover: {s.get('R', 1400)},\n"
                f"        expected: {exp},\n        old_1_0_0_ok: {str(c['v100'] == c['mcl']).lower()},\n        old_1_1_0_ok: {b},\n    }},\n")
    f.write("];\n")
for c in cases:
    print(f"{c['name']:<34} I={c['I']} {c['scheme']}  mcl={len(c['mcl'])} v1.0.0={'ok' if c['v100']==c['mcl'] else len(c['v100'])} "
          f"v1.1.0={'n/a' if c['v110'] is None else ('ok' if c['v110']==c['mcl'] else len(c['v110']))}  lines={c['abc'].count(chr(10))}")
